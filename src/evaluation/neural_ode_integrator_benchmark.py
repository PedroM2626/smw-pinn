def aux_dim_for(state_dim: int = 8) -> int:
    """Channels the base net emits: the two acceleration components and the contact logits."""
    return state_dim - 2


def build_arm(
    family: str,
    solver: str,
    mechanism: str,
    state_dim: int,
    action_dim: int,
    latent_dim: int = 64,
    fno_width: int = 32,
    fno_modes: int = 6,
    fno_layers: int = 2,
) -> NeuralODEDynamics:
    """One cell: the family's network read as an acceleration field, under one integrator."""
    sensor_dim = state_dim + action_dim
    aux_dim = aux_dim_for(state_dim)
    base: nn.Module
    if family == "MLP":
        base = StatisticalMLPDynamics(
            state_dim=aux_dim, action_dim=action_dim, sensor_dim=sensor_dim
        )
    elif family == "DeepONet":
        base = DeepONetDynamics(
            state_dim=aux_dim, action_dim=action_dim, latent_dim=latent_dim, sensor_dim=sensor_dim
        )
    elif family == "FNO":
        base = FNODynamics(
            state_dim=aux_dim,
            action_dim=action_dim,
            width=fno_width,
            modes=fno_modes,
            n_layers=fno_layers,
            sensor_dim=sensor_dim,
        )
    else:
        raise ValueError(f"unknown family {family!r}")
    return NeuralODEDynamics(
        base=base,
        state_dim=state_dim,
        action_dim=action_dim,
        solver=solver,
        bounded=(mechanism == "bounded"),
        subpixels_per_pixel=SUBPIXELS_PER_PIXEL,
        max_vx=MAX_VX,
        terminal_vy=TERMINAL_VY,
        min_vy=MIN_VY,
    )


def second_order_coefficient(
    moved: np.ndarray, velocity: np.ndarray, accel: np.ndarray
) -> Dict[str, float]:
    r"""The slope $c$ in $\hat x = x + v/16 + c\,\hat a/16$, fitted without an intercept.

    `moved`, `velocity` and `accel` are $[N, 2]$: the position increment, the velocity the
    step started with and the acceleration the same model reported. Fitting $c$ from the
    trained model rather than reading it off the method's algebra is the point - it says what
    the arm *actually does* on real states, and it gives the console the same estimator, so
    "the engine is forward Euler" becomes a measured slope with the same units as the arms.
    """
    moved = np.asarray(moved, dtype=np.float64)
    velocity = np.asarray(velocity, dtype=np.float64)
    accel = np.asarray(accel, dtype=np.float64)
    residual = SUBPIXELS_PER_PIXEL * moved - velocity
    out: Dict[str, float] = {}
    for channel, name in ((0, "x"), (1, "y")):
        a = accel[:, channel]
        denominator = float(np.dot(a, a))
        out[f"c_{name}"] = (
            float(np.dot(residual[:, channel], a) / denominator) if denominator else None
        )
    pooled_a = accel.reshape(-1)
    pooled_r = residual.reshape(-1)
    denominator = float(np.dot(pooled_a, pooled_a))
    out["c_pooled"] = float(np.dot(pooled_r, pooled_a) / denominator) if denominator else None
    return out


@torch.no_grad()
def one_step_metrics(
    model: NeuralODEDynamics, data: Dict[str, Any], device: torch.device
) -> Dict[str, float]:
    """The shared held-out battery, plus the integrator's own measured coefficient."""
    model.eval()
    states = torch.as_tensor(data["test_states"], dtype=torch.float32, device=device)
    actions = torch.as_tensor(data["test_actions"], dtype=torch.float32, device=device)
    targets = torch.as_tensor(data["test_next_states"], dtype=torch.float32)
    pred = model(states, actions).cpu()
    s = np.asarray(data["test_states"], dtype=np.float64)
    ns = np.asarray(data["test_next_states"], dtype=np.float64)
    out = prediction_metrics(pred.numpy(), s, ns, compute_per_variable_metrics(pred, targets))
    accel = pred[:, 2:4].numpy() - s[:, 2:4]
    out.update(second_order_coefficient(pred[:, :2].numpy() - s[:, :2], s[:, 2:4], accel))
    return out


def console_coefficient(data: Dict[str, Any]) -> Dict[str, float]:
    r"""The same estimator applied to the recorded transitions themselves.

    Reported with the exact-frame rate and with the contact-free subset, because the slope on
    its own is a tail statistic: a handful of frames where the engine stops, terminates or
    wraps a screen carry both the largest displacement error and the largest acceleration, and
    they are what moves a least-squares $c$ off zero. Reading the console as an integrator
    therefore needs the distribution, not the coefficient - and the distribution is reported
    twice, once over every held-out frame and once over the frames where no contact flag is
    set, because "the contact-free slope is 0.0000" is only a claim about the engine if the
    frames that make it up are counted.
    """
    s = np.asarray(data["test_states"], dtype=np.float64)
    ns = np.asarray(data["test_next_states"], dtype=np.float64)
    contact_free = (s[:, 4:8] < 0.5).all(axis=1)
    out = second_order_coefficient(ns[:, :2] - s[:, :2], s[:, 2:4], ns[:, 2:4] - s[:, 2:4])
    out.update(
        {
            f"{key}_contact_free": value
            for key, value in second_order_coefficient(
                (ns - s)[:, :2][contact_free],
                s[:, 2:4][contact_free],
                (ns - s)[:, 2:4][contact_free],
            ).items()
        }
    )
    for mask, suffix in ((np.ones(s.shape[0], dtype=bool), ""), (contact_free, "_contact_free")):
        for channel, axis in ((0, "x"), (1, "y")):
            residual = SUBPIXELS_PER_PIXEL * (ns[:, channel] - s[:, channel]) - s[:, 2 + channel]
            residual = residual[mask]
            moving = np.abs((ns - s)[:, 2 + channel][mask]) > 2.0
            broken = moving & (np.abs(residual) >= EXACT_SUBPIXELS)
            out[f"n_frames_{axis}{suffix}"] = float(residual.size)
            out[f"exact_rate_{axis}{suffix}"] = float(np.mean(np.abs(residual) < EXACT_SUBPIXELS))
            out[f"n_accelerating_{axis}{suffix}"] = float(moving.sum())
            out[f"n_holding_the_slope_{axis}{suffix}"] = float(broken.sum())
            out[f"mean_residual_of_those_{axis}{suffix}"] = (
                float(np.mean(residual[broken])) if broken.any() else 0.0
            )
    return out


def _contrasts(runs: Dict[int, Dict[str, Dict[str, Any]]], metric: str) -> Dict[str, Any]:
    """Solver-vs-solver and mechanism-vs-mechanism contrasts inside the grid, paired by seed."""
    named = {
        "euler_vs_symplectic": ("euler/free", "symplectic/free"),
        "euler_vs_midpoint": ("euler/free", "midpoint/free"),
        "euler_vs_rk4": ("euler/free", "rk4/free"),
        "rk4_vs_symplectic": ("rk4/free", "symplectic/free"),
        "bounded_vs_free": ("euler/free", "euler/bounded"),
        "bounded_vs_free_rk4": ("rk4/free", "rk4/bounded"),
    }
    ran = _families_in(runs.get(min(runs), {})) if runs else FAMILIES
    return {
        family: {
            name: _paired(
                _series(runs, arm_label(family, *left.split("/")), metric),
                _series(runs, arm_label(family, *right.split("/")), metric),
            )
            for name, (left, right) in named.items()
        }
        for family in ran
    }


def _parity_with_convention_study(runs: Dict[int, Dict[str, Dict[str, Any]]]) -> Dict[str, Any]:
    """Do the euler and symplectic arms reproduce the two arms they are coded to equal?

    The model-level parity is in `tests/test_neural_ode_dynamics.py`; this is the same claim
    after training, against the artifact 10.53 published for the identical weights, so a
    difference in the data pipeline or the optimizer would show up here instead of passing
    unnoticed.
    """
    path = os.path.join(RESULTS_DIR, CONVENTION_ARTIFACT_NAME)
    if not os.path.isfile(path):
        return {"available": False, "reason": f"{CONVENTION_ARTIFACT_NAME} not found"}
    reference = read_metrics(path).get("per_seed", {})
    gaps: List[float] = []
    rows: Dict[str, Any] = {}
    for family in _families_in(runs.get(min(runs), {})) if runs else FAMILIES:
        for solver, cell in (("euler", "carried"), ("symplectic", "next")):
            reference_cell = f"{family}/{cell}/none"
            mine, theirs = [], []
            for seed, record in sorted(runs.items()):
                got = record.get(arm_label(family, solver, "free"))
                want = reference.get(str(seed), {}).get(reference_cell)
                if got is None or want is None:
                    continue
                mine.append(got["drift_multistart_mean_px"])
                theirs.append(want["drift_multistart_mean_px"])
            if mine:
                gap = float(np.max(np.abs(np.asarray(mine) - np.asarray(theirs))))
                gaps.append(gap)
                rows[f"{family}/{solver}"] = {
                    "reference_cell": reference_cell,
                    "n_seeds_compared": len(mine),
                    "max_abs_drift_difference_px": gap,
                }
    return {
        "available": True,
        "reference_artifact": f"results/{CONVENTION_ARTIFACT_NAME}",
        "per_cell": rows,
        "worst_abs_drift_difference_px": max(gaps) if gaps else None,
        "identical": bool(gaps) and max(gaps) == 0.0,
    }


def _families_in(record_owner: Dict[str, Any]) -> Tuple[str, ...]:
    """The families that actually ran, so a partial smoke run cannot index a missing cell."""
    return tuple(f for f in FAMILIES if any(str(key).startswith(f + "/") for key in record_owner))


def _mean_of_dicts(blocks: Sequence[Dict[str, float]]) -> Dict[str, float]:
    keys = list(blocks[0])
    return {key: float(np.mean([block[key] for block in blocks])) for key in keys}


def _verdict(summary: Dict[str, Any], console: Dict[str, float]) -> Dict[str, Any]:
    """Prose built only from cells that were measured."""
    families = _families_in(summary)
    free = {arm: block for arm, block in summary.items() if arm.endswith("/free")}
    by_solver = {
        solver: {
            "measured_c": float(
                np.mean([free[f"{f}/{solver}/free"]["c_pooled"]["mean"] for f in families])
            ),
            "expected_c": EXPECTED_C[solver],
            "position_px": float(
                np.mean([free[f"{f}/{solver}/free"]["x_mae_px"]["mean"] for f in families])
            ),
            "drift_px": float(
                np.mean(
                    [
                        free[f"{f}/{solver}/free"]["drift_multistart_mean_px"]["mean"]
                        for f in families
                    ]
                )
            ),
            "violation_at_tightest": float(
                np.mean(
                    [
                        free[f"{f}/{solver}/free"][f"published_violation_at_{0.002:g}px"]["mean"]
                        for f in families
                    ]
                )
            ),
        }
        for solver in SOLVERS
    }
    best = min(by_solver, key=lambda s: by_solver[s]["position_px"])
    bounded = {
        solver: float(
            np.mean(
                [
                    summary[f"{f}/{solver}/bounded"]["out_of_bounds_rate"]["mean"]
                    - summary[f"{f}/{solver}/free"]["out_of_bounds_rate"]["mean"]
                    for f in families
                ]
            )
        )
        for solver in SOLVERS
    }
    return {
        "per_solver_free_cells": by_solver,
        "console_measured_c": console["c_pooled"],
        "console_measured_c_x": console["c_x"],
        "console_measured_c_x_contact_free": console["c_x_contact_free"],
        "console_exact_identity_rate_x": console["exact_rate_x"],
        "console_frames_holding_the_slope_x": console["n_holding_the_slope_x"],
        "console_frames_x": console["n_frames_x"],
        "exact_continuous_c": EXACT_CONTINUOUS_C,
        "best_position_solver": best,
        "out_of_bounds_change_by_bounding": bounded,
        "reading": (
            f"{len(summary)} cells of the integrator grid were trained under one protocol. The "
            f"console's own second-order coefficient, fitted the same least-squares way as every "
            f"arm's, is {console['c_x']:.4f} horizontally and {console['c_pooled']:.4f} pooled, "
            f"near the {EXACT_CONTINUOUS_C} of a second-order method. That slope is a tail "
            f"statistic, not the engine's rule: it comes from "
            f"{console['n_holding_the_slope_x']:.0f} of {console['n_frames_x']:.0f} frames "
            f"(mean residual {console['mean_residual_of_those_x']:.2f} subpixels) while "
            f"{console['exact_rate_x'] * 100:.1f}% of frames satisfy the first-order identity "
            f"exactly, and on contact-free frames alone the slope is "
            f"{console['c_x_contact_free']:.4f}. The arms measure "
            + ", ".join(f"{s} {by_solver[s]['measured_c']:.3f}" for s in SOLVERS)
            + f"; the lowest held-out position error is {best} at "
            f"{by_solver[best]['position_px']:.4f} px. Projecting the bounds inside the step "
            f"changes the out-of-bounds rate by "
            + ", ".join(f"{s} {bounded[s]:+.3f}" for s in SOLVERS)
            + "."
        ),
    }


