r"""
neural_ode_integrator_benchmark.py
Which numerical method is the SNES engine? A learned vector field, four solvers (10.55).

Section 10.53 showed that a whole line of this repository's physics results turns on one
typed-in choice: whether the graph advances position with the velocity the frame starts with
(`carried`, what the console does) or with the velocity the network predicts for the frame
after (`next`, what every hard shell since 10.27 does). It compared the two by *declaring*
them. `NeuralODEDynamics` instead learns a continuous field - $dx/dt = v_x/16$,
$dv_x/dt = a_x(s, a)$ - and hands the choice to a named integrator, so the convention becomes
a solver option with a textbook name and a known order:

    euler        $c = 0$     forward Euler, position with the velocity it started with
    midpoint     $c = \tfrac12$  the field re-evaluated half a step in
    rk4          $c = \tfrac12$  classical Runge-Kutta, four evaluations
    symplectic   $c = 1$     velocity first, then position - the published shell's split

where $c$ is the coefficient of the second-order term each method adds to the position step,
$\hat x_{t+1} = x_t + v_t/16 + c\,\hat a/16$ for a field of constant acceleration. The
exact solution of the posited ODE has $c = \tfrac12$, and 10.49 measured the console at
$c \approx 0$: the engine is not integrating this ODE accurately, it is truncating it at
first order. So the four arms are not four approximations of one truth - they are four
*different discrete systems*, and this study asks which one the data is generated by and
whether matching the engine's truncation beats modelling the physics better than the engine
does.

Two things can only be measured this way:

* the **measured** $c$ of every arm and of the console, from the trained models themselves
  rather than from the algebra, so the claim "the console is forward Euler" is a slope;
* whether the bounds belong **inside** the step. The published shells clamp the velocity the
  network reports, after the arithmetic; `bounded` projects the state inside the integration,
  where the engine saturates it, which is the first time this repository tests that position.

Three families x four solvers x {free, bounded} = 24 arms, five seeds, the protocol of
10.42/10.47/10.53 unchanged, and the same arm of 10.53 read from its artifact as the control
for each solver, so parity is checked on trained weights and not only in code.

Writes ``results/neural_ode_integrator_metrics.json``. Emulator-free.
"""

