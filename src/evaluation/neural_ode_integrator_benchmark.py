def run_neural_ode_integrator_benchmark(
    dataset_path: str = DATASET_GAMEPLAY,
    output_dir: Optional[str] = None,
    epochs: int = 35,
    batch_size: int = 128,
    patience: int = 8,
    learning_rate: float = 1e-3,
    weight_decay: float = 1e-4,
    rollout_horizon: int = 120,
    num_rollout_starts: int = 10,
    seeds: Sequence[int] = DEFAULT_SEEDS,
    latent_dim: int = 64,
    fno_width: int = 32,
    fno_modes: int = 6,
    fno_layers: int = 2,
    save_checkpoints: bool = True,
    only_arms: Optional[Sequence[str]] = None,
) -> Dict[str, Any]:
    """Train and score every cell of the integrator grid."""
    out_dir = output_dir or RESULTS_DIR
    draws = list(seeds)
    plan = training_plan()
    if only_arms:
        wanted = {str(name).strip() for name in only_arms}
        plan = [item for item in plan if item[0] in wanted or item[1] in wanted]
    logger.info("=== NeuralODE integrator grid: %d arms x %d seeds ===", len(plan), len(draws))

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    os.makedirs(out_dir, exist_ok=True)
    evaluator = RolloutEvaluator(device=device)
    checkpoint_dir = os.path.join(out_dir, "checkpoints")
    scratch = os.path.join(tempfile.gettempdir(), f"mworld_neuralode_scratch_{os.getpid()}")
    os.makedirs(scratch, exist_ok=True)

    runs: Dict[int, Dict[str, Dict[str, Any]]] = {}
    console_rows: List[Dict[str, float]] = []
    real_reference: Optional[np.ndarray] = None
    reference_data: Optional[Dict[str, Any]] = None
    for draw in draws:
        runs[draw] = {}
        for label, family, solver, mechanism in plan:
            set_global_seed(draw)
            data = load_and_preprocess_data(dataset_path=dataset_path, seed=draw)
            train_loader, val_loader, test_loader = create_dataloaders(
                data, batch_size=batch_size, seed=draw
            )
            state_dim = int(data["train_states"].shape[1])
            action_dim = int(data["train_actions"].shape[1])
            if family == "MLP" and solver == SOLVERS[0] and mechanism == "free":
                console_rows.append(console_coefficient(data))
                if reference_data is None:
                    reference_data = data
                if real_reference is None:
                    H = int(min(rollout_horizon, len(data["test_actions"])))
                    real_reference = _real_reference(
                        data["test_states"],
                        data["test_actions"],
                        data["test_next_states"],
                        H,
                        num_rollout_starts,
                    )
            H = int(min(rollout_horizon, len(data["test_actions"])))
            model = build_arm(
                family,
                solver,
                mechanism,
                state_dim,
                action_dim,
                latent_dim,
                fno_width,
                fno_modes,
                fno_layers,
            )
            slug = f"ode_{label.replace('/', '_').lower()}"
            primary = draw == draws[0] and save_checkpoints and publishes(label)
            trainer = DynamicsTrainer(
                model=model,
                model_type=slug if primary else f"{slug}_s{draw}",
                device=device,
                learning_rate=learning_rate,
                weight_decay=weight_decay,
                loss_fn=build_loss("none"),
                save_dir=checkpoint_dir if primary else scratch,
            )
            t0 = time.time()
            trainer.fit(
                train_loader=train_loader, val_loader=val_loader, epochs=epochs, patience=patience
            )
            metrics = trainer.evaluate(test_loader)
            multi = evaluator.evaluate_rollout_multistart(
                model=model,
                model_type="operator_feedforward",
                states=data["test_states"],
                actions=data["test_actions"],
                next_states=data["test_next_states"],
                horizon=H,
                num_starts=num_rollout_starts,
            )
            trajectories = _rollout_trajectories(
                model,
                evaluator,
                data["test_states"],
                data["test_actions"],
                data["test_next_states"],
                H,
                num_rollout_starts,
            )
            record: Dict[str, Any] = {
                "parameters": sum(p.numel() for p in model.parameters() if p.requires_grad),
                "field_evaluations": model.field_evaluations,
                "test_loss_data": metrics["val_loss_data"],
                "test_kinematic_error": metrics["val_loss_kinematics"],
                "drift_multistart_mean_px": float(multi["mean_drift_mean"]),
                "drift_multistart_final_px": float(multi["final_drift_mean"]),
                "kinematic_violation_rate": float(multi["kinematic_violation_rate_mean"]),
                "velocity_violation_rate": float(multi["velocity_violation_rate_mean"]),
            }
            record.update(one_step_metrics(model, data, device))
            record.update(
                _velocity_compliance(model, data["test_states"], data["test_actions"], device)
            )
            record.update(rollout_violations(trajectories))
            decomposition = aggregate(trajectories)
            decomposition.pop("published_violation_rate", None)
            record["decomposition"] = decomposition
            record["test_seconds"] = time.time() - t0
            runs[draw][label] = record
            logger.info(
                "seed %d | %-28s | loss %.4f | xerr %.4f px | c %.4f | drift %.1f px | viol@.002 %.4f",
                draw,
                label,
                record["test_loss_data"],
                record["x_mae_px"],
                record["c_pooled"],
                record["drift_multistart_mean_px"],
                record["published_violation_at_0.002px"],
            )
    shutil.rmtree(scratch, ignore_errors=True)

    flat_keys = (
        "parameters",
        "field_evaluations",
        "test_loss_data",
        "test_kinematic_error",
        "drift_multistart_mean_px",
        "drift_multistart_final_px",
        "kinematic_violation_rate",
        "velocity_violation_rate",
        "out_of_bounds_rate",
        "max_abs_vx_predicted",
        "test_seconds",
        "x_mae_px",
        "y_mae_px",
        "vx_mae_px",
        "vy_mae_px",
        "c_ground_accuracy",
        "effective_vx_mae_subpx",
        "effective_vy_mae_subpx",
        "x_effective_exact_rate",
        "y_effective_exact_rate",
        "metrics_position_subpx",
        "metrics_velocity_subpx",
        "c_x",
        "c_y",
        "c_pooled",
        *rollout_violation_keys(),
    )
    summary: Dict[str, Any] = {}
    for label, *_ in plan:
        if not _series(runs, label, "drift_multistart_mean_px"):
            continue
        block: Dict[str, Any] = {key: _aggregate(runs, label, key) for key in flat_keys}
        block["decomposition"] = _mean_of_dicts(
            [runs[s][label]["decomposition"] for s in sorted(runs) if label in runs[s]]
        )
        summary[label] = block

    console = _mean_of_dicts(console_rows) if console_rows else {}
    if real_reference is not None and reference_data is not None:
        console.update(rollout_violations(real_reference))
        console.update(aggregate(real_reference))
        console.update(_console_position_row(reference_data))

    payload: Dict[str, Any] = {
        "study": (
            "Which numerical method does the engine use? A learned continuous vector field "
            "integrated by four named solvers, family x solver x bounding over "
            f"{len(draws)} seeds."
        ),
        "protocol": {
            "dataset_path": dataset_path,
            "epochs": epochs,
            "batch_size": batch_size,
            "seeds": draws,
            "patience": patience,
            "learning_rate": learning_rate,
            "weight_decay": weight_decay,
            "rollout_horizon": int(rollout_horizon),
            "num_rollout_starts": num_rollout_starts,
            "latent_dim": latent_dim,
            "fno_width": fno_width,
            "fno_modes": fno_modes,
            "fno_layers": fno_layers,
            "solvers": {
                solver: {
                    "expected_second_order_coefficient": EXPECTED_C[solver],
                    "field_evaluations_per_step": FIELD_EVALUATIONS[solver],
                }
                for solver in SOLVERS
            },
            "exact_continuous_c": EXACT_CONTINUOUS_C,
            "subpixels_per_pixel": SUBPIXELS_PER_PIXEL,
            "tolerances_px": list(TOLERANCE_LADDER),
            "published_tolerance_px": PUBLISHED_TOLERANCE_PX,
            "exact_subpixels": EXACT_SUBPIXELS,
            "published_checkpoints": [
                checkpoint_name(label) for label, *_ in plan if publishes(label)
            ],
        },
        "per_seed": {str(s): runs[s] for s in sorted(runs)},
        "console_coefficient": console,
        "summary": summary,
        "contrasts_drift_px": _contrasts(runs, "drift_multistart_mean_px"),
        "contrasts_x_mae_px": _contrasts(runs, "x_mae_px"),
        "contrasts_effective_vx_mae_subpx": _contrasts(runs, "effective_vx_mae_subpx"),
        "integrator_vs_convention_study": _parity_with_convention_study(runs),
        "verdict": _verdict(summary, console),
    }
    if _render_figure(summary, console, os.path.join(out_dir, "figures", FIGURE_NAME)):
        payload["figure"] = f"results/figures/{FIGURE_NAME}"

    command = (
        "python -m src.evaluation.neural_ode_integrator_benchmark"
        f" --seeds {','.join(str(s) for s in draws)}"
    )
    if only_arms:
        command += f" --arms {','.join(only_arms)}"
    artifact = os.path.join(out_dir, ARTIFACT_NAME)
    write_metrics(artifact, payload, seed=draws[0], command=command)
    logger.info("Metrics written to %s", artifact)
    return payload


def rollout_violation_keys() -> Tuple[str, ...]:
    return tuple(
        f"published_violation_at_{tolerance:g}px" for tolerance in TOLERANCE_LADDER
    ) + tuple(f"next_velocity_violation_at_{tolerance:g}px" for tolerance in TOLERANCE_LADDER)


def _console_position_row(data: Dict[str, Any]) -> Dict[str, float]:
    """The console scored with the same held-out battery the arms use."""
    s = np.asarray(data["test_states"], dtype=np.float64)
    ns = np.asarray(data["test_next_states"], dtype=np.float64)
    per_variable = compute_per_variable_metrics(
        torch.as_tensor(ns, dtype=torch.float32), torch.as_tensor(ns, dtype=torch.float32)
    )
    return prediction_metrics(ns, s, ns, per_variable)


def _render_figure(summary: Dict[str, Any], console: Dict[str, float], path: str) -> bool:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    free = [arm for arm in summary if arm.endswith("/free")]
    if not free:
        return False
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.8))
    colors = {"MLP": "#8ab4f8", "DeepONet": "#41d19a", "FNO": "#f6c445"}
    width = 0.25
    families = sorted({arm.split("/")[0] for arm in summary})
    for i, family in enumerate(families):
        position = [summary[f"{family}/{s}/free"]["x_mae_px"]["mean"] for s in SOLVERS]
        axes[0].bar(
            np.arange(len(SOLVERS)) + (i - 1) * width,
            position,
            width,
            color=colors[family],
            label=family,
        )
    axes[0].axhline(console["x_mae_px"], ls="--", color="#333333", label="console")
    axes[0].set_xticks(range(len(SOLVERS)))
    axes[0].set_xticklabels(SOLVERS)
    axes[0].set_ylabel("held-out position error (px)")
    axes[0].set_yscale("log")
    axes[0].legend(fontsize=7)

    for i, family in enumerate(families):
        measured = [summary[f"{family}/{s}/free"]["c_pooled"]["mean"] for s in SOLVERS]
        axes[1].plot(
            range(len(SOLVERS)),
            measured,
            marker="o",
            color=colors[family],
            label=f"{family} measured $c$",
        )
    axes[1].axhline(EXACT_CONTINUOUS_C, ls="--", color="#333333", label="exact ODE solution")
    axes[1].axhline(console["c_pooled"], ls=":", color="#e06666", label="console measured $c$")
    axes[1].axhline(0.0, ls="-.", color="#666666", label="forward Euler")
    axes[1].axhline(1.0, ls="-.", color="#999999", label="velocity-first split")
    axes[1].set_xticks(range(len(SOLVERS)))
    axes[1].set_xticklabels(SOLVERS)
    axes[1].set_ylabel("second-order coefficient $c$")
    axes[1].legend(fontsize=7)
    fig.suptitle("A learned vector field under four integrators (README 10.55)")
    fig.tight_layout()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, dpi=160)
    plt.close(fig)
    return True


