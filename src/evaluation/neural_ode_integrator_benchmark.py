def render_cross_study_closed_loop(
    ode_payload: Dict[str, Any], convention_payload: Dict[str, Any]
) -> List[str]:
    r"""The same convention, trained twice: this study's solver against 10.53's arm.

    `euler` integrates the carried velocity and `symplectic` the next one, so each pair here is
    one cell of 10.53's closed-loop table re-trained through a second code path and flown with
    the same planner. The difference column is not a treatment effect - it is the size of the
    reproducibility error the two paths have, and it is what the 10.55 closed-loop claims have
    to be read against.
    """
    rows: List[str] = []
    mine = ode_payload["multi_seed"]["per_model"]
    theirs = convention_payload["multi_seed"]["per_model"]
    for family in ("mlp", "deeponet", "fno"):
        for solver, cell in (("euler", "carried_none"), ("symplectic", "next_none")):
            reference, other = f"{family}_{cell}", f"{family}_{solver}_free"
            if reference not in theirs or other not in mine:
                continue
            a, b = theirs[reference], mine[other]
            rows.append(
                rf"| {family} | 10.53 `{reference}`"
                rf" | {a['progress_px_mean']:.2f} $\pm$ {a['progress_px_std']:.2f}"
                rf" | {a['pit_or_death']}"
                rf" | 10.55 `{other}`"
                rf" | {b['progress_px_mean']:.2f} $\pm$ {b['progress_px_std']:.2f}"
                rf" | {b['pit_or_death']}"
                rf" | {b['progress_px_mean'] - a['progress_px_mean']:+.2f} px |"
            )
    return rows


