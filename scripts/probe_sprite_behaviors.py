"""
probe_sprite_behaviors.py - measure what every sprite the stages spawn does to Mario, off the engine.

The dashboard's enemy marker used to draw whichever sprite the hazard probe found nearest - any
slot with status >= 8, whatever it held: a springboard, a bouncing block and a power-up all read
as "enemy", and every enemy but the nearest was invisible. This probe replaces the guess with
measurement: it walks each recorded stage until it meets each distinct sprite id, saves the frame,
and then touches that sprite from the side and from above, reading the engine's own answers -
the death mode, the powerup state, the coin counter, the sprite's status byte and whether a
falling Mario bounced off it.

What is measured per sprite id:

* side contact: does touching the sprite from the side hurt a small Mario (death mode 0x0B)?
* the stomp: does Mario falling onto the sprite survive (and does the sprite's status byte show
  it died), does he bounce (his vy flips), or does the sprite hold him up like a platform?
* the pickup: does the sprite vanish and pay a coin or a power-up?
* nothing: a sprite the engine lets Mario pass through without consequence - the "block that is
  not an enemy" the old panel drew red.

Writes `results/sprite_behavior_probe_metrics.json`, the table the recorder and the panel then
classify every sprite slot through (`src.environment.sprite_behavior`).

Run:  python -m scripts.probe_sprite_behaviors
      python -m scripts.probe_sprite_behaviors --ids 0x05,0x2C
"""

import argparse
import os
import sys
from typing import Any, Dict, List, Optional, Tuple

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch  # noqa: E402

from src.environment import wram  # noqa: E402
from src.environment.snes_emulator import SnesLibretroEmulator  # noqa: E402
from src.utils.logging import get_logger  # noqa: E402
from src.utils.paths import CORE_PATH, ROM_PATH, results_file, state_path  # noqa: E402
from src.utils.provenance import write_metrics  # noqa: E402

logger = get_logger(__name__)

#: frames of stage walking between sprite encounters before the sweep gives up on that stage
WALK_FRAMES = 900
#: frames each contact probe runs before its answer is read
CONTACT_FRAMES = 45
#: the coin counter is one byte at $7E:0DBF
ADDR_COINS = 0x0DBF
#: the stage savestates whose sprite populations this measures
STAGES = (
    ("0x2A", "smw_map_node_152_136_t2a.state"),
    ("0x29", "smw_map_node_68_135_t29.state"),
    ("0x27", "smw_map_round_1_152_104_t27.state"),
    ("0x28", "smw_map_node_116_126_t28.state"),
)


def sprite_slots(emu: SnesLibretroEmulator, plausible_only: bool = False) -> List[Dict[str, Any]]:
    """Every live sprite slot, through the one reader the rest of the repository shares.

    `plausible_only` keeps only slots whose position has settled inside a level; a probe that
    trusted a fresh slot's coordinates would measure the fall out of the world instead of a
    contact.
    """
    from src.environment.sprite_behavior import live_slots

    slots = live_slots(emu)
    return slots if plausible_only else [{**s} for s in _all_slots(emu)]


def _all_slots(emu: SnesLibretroEmulator) -> List[Dict[str, Any]]:
    """Every slot with a nonzero status byte, plausible position or not."""
    out = []
    for slot in range(wram.NUM_SPRITE_SLOTS):
        status = emu.read_wram_u8(wram.ADDR_SPRITE_STATUS + slot)
        if status == 0:
            continue
        out.append(
            {
                "slot": slot,
                "id": emu.read_wram_u8(wram.ADDR_SPRITE_ID + slot),
                "status": status,
                "x": emu.read_wram_u16_le(wram.ADDR_SPRITE_X_LOW + slot)
                | (emu.read_wram_u8(wram.ADDR_SPRITE_X_HIGH + slot) << 8),
                "y": emu.read_wram_u16_le(wram.ADDR_SPRITE_Y_LOW + slot)
                | (emu.read_wram_u8(wram.ADDR_SPRITE_Y_HIGH + slot) << 8),
            }
        )
    return out


TABLE_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "src",
    "environment",
    "sprite_behavior_table.py",
)


def emit_table(records: List[Dict[str, Any]]) -> str:
    """Write the measured sprite classes as the Python module the runtime classifies through.

    Generated by `python -m scripts.probe_sprite_behaviors --emit-table`; do not edit by hand.
    `tests/test_sprite_behavior.py` gates the module against the artifact.
    """
    lines = [
        '"""sprite_behavior_table.py - the measured sprite behaviour table.',
        "",
        "Generated by `python -m scripts.probe_sprite_behaviors --emit-table`; do not edit by hand.",
        "Each entry is what the engine itself did when the probe met that sprite in its own stage",
        "and touched it from the side and from above, with and without the sprite present: see",
        "`results/sprite_behavior_probe_metrics.json` for the raw measurements and the protocol.",
        "",
        "An id absent from this table has not been measured yet and is reported as `unprobed`.",
        '"""',
        "",
        "BEHAVIOR = {",
    ]
    for record in sorted(records, key=lambda r: int(r["sprite"], 16)):
        lines.append(f'    {record["sprite"]}: "{record["class"]}",')
    lines.append("}")
    lines.append("")
    path = os.path.normpath(TABLE_PATH)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return path


def teleport(emu: SnesLibretroEmulator, x: int, y: int) -> None:
    emu.write_wram_u16_le(wram.ADDR_PLAYER_X, x)
    emu.write_wram_u16_le(wram.ADDR_PLAYER_Y, y)
    emu.write_wram_u8(wram.ADDR_PLAYER_X_SUB, 0)
    emu.write_wram_u8(wram.ADDR_PLAYER_Y_SUB, 0)
    emu.write_wram_u8(wram.ADDR_VX, 0)
    emu.write_wram_u8(wram.ADDR_VY, 0)


def sprite_at(emu: SnesLibretroEmulator, sprite_id: int) -> Optional[Dict[str, Any]]:
    """The first live slot holding this id right now, with its position."""
    for sprite in sprite_slots(emu):
        if sprite["id"] == sprite_id:
            return sprite
    return None


#: the death animation's mode byte - the one mode that means contact killed the player
DEATH_MODE = 0x0B
#: the eight channels of the player record, for the 10.63 held-player signature
HOLD_KEYS = ("x", "y", "vx", "vy", "c_ground", "c_ceiling", "c_left", "c_right")
#: consecutive identical player records that mean the engine opened one of its own boxes
FROZEN_RUN = 30


def contact_probe(
    emu: SnesLibretroEmulator, frame_bytes: bytes, sprite_id: int, with_sprite: bool = True
) -> Dict[str, Any]:
    """Touch the sprite from the side and read what the engine did to a small Mario.

    The probe runs twice - once with the sprite and once with its slot cleared - because a
    teleport next to a sprite that floats past the stage's floor (the chimney smoke over the
    Yoshi's House roof) kills Mario by the fall, not by the contact, and only the difference
    between the two runs is the sprite's doing. It also watches for the 10.63 held-player
    signature: the engine's own message boxes freeze the whole player record with the mode still
    `0x14`, which is what touching the message block does.
    """
    emu.load_state(frame_bytes)
    sprite = sprite_at(emu, sprite_id)
    if sprite is None:
        return {"ran": False}
    if not with_sprite:
        emu.write_wram_u8(wram.ADDR_SPRITE_STATUS + sprite["slot"], 0)
    teleport(emu, sprite["x"] - 12, sprite["y"] - 8)

    last = None
    run = 0
    frozen = False
    for _ in range(CONTACT_FRAMES):
        emu.set_input({})
        emu.step_frame()
        state = emu.get_smw_state()
        record = tuple(round(float(state[k]), 4) for k in HOLD_KEYS)
        if record == last:
            run += 1
        else:
            run = 0
        last = record
        frozen = frozen or run >= FROZEN_RUN
        if emu.get_game_mode() == DEATH_MODE:
            break
    return {
        "ran": True,
        "mario_died": emu.get_game_mode() == DEATH_MODE,
        "final_mode": f"{emu.get_game_mode():#04x}",
        "final_y": round(float(emu.get_smw_state()["y"]), 1),
        "froze_the_player": bool(frozen),
    }


def stomp_probe(
    emu: SnesLibretroEmulator, frame_bytes: bytes, sprite_id: int, with_sprite: bool = True
) -> Dict[str, Any]:
    """Fall onto the sprite from above and read what the engine did to both of them.

    Runs with and without the sprite for the same reason the contact probe does: a stomp that
    lands past the floor kills by the fall, and only the difference is the sprite's. The frozen
    watch is here too - landing on the message block opens its box.
    """
    emu.load_state(frame_bytes)
    sprite = sprite_at(emu, sprite_id)
    if sprite is None:
        return {"ran": False}
    status_before = int(sprite["status"])
    if not with_sprite:
        emu.write_wram_u8(wram.ADDR_SPRITE_STATUS + sprite["slot"], 0)
    teleport(emu, sprite["x"] - 4, sprite["y"] - 72)
    bounced = False
    last = None
    run = 0
    frozen = False
    for _ in range(CONTACT_FRAMES):
        emu.set_input({})
        emu.step_frame()
        state = emu.get_smw_state()
        vy = state["vy"]
        bounced = bounced or vy < -2.0
        record = tuple(round(float(state[k]), 4) for k in HOLD_KEYS)
        if record == last:
            run += 1
        else:
            run = 0
        last = record
        frozen = frozen or run >= FROZEN_RUN
        if emu.get_game_mode() == DEATH_MODE:
            break
    after = sprite_at(emu, sprite_id) if with_sprite else None
    state = emu.get_smw_state()
    return {
        "ran": True,
        "mario_died": emu.get_game_mode() == DEATH_MODE,
        "final_mode": f"{emu.get_game_mode():#04x}",
        "final_y": round(float(state["y"]), 1),
        "bounced": bool(bounced),
        "held_up": bool(state["c_ground"] > 0.5),
        "rest_y": round(float(state["y"]), 1),
        "froze_the_player": bool(frozen),
        "sprite_status_before": status_before,
        "sprite_status_after": None if after is None else int(after["status"]),
        "sprite_gone": after is None,
    }


def classify(
    contact: Dict[str, Any],
    contact_without: Dict[str, Any],
    stomp: Dict[str, Any],
    stomp_without: Dict[str, Any],
) -> str:
    """The behaviour class the panel draws, derived only from the measured difference.

    A run that kills Mario with the sprite and without it alike says nothing about the sprite:
    the terrain killed him. What only the sprite's presence produces is the class:

    * ``hostile`` - contact killed a small Mario the cleared run survived;
    * ``interact`` - the engine opened one of its own boxes and froze the player (10.63's
      signature, the mode still `0x14`) with the sprite present and not with its slot cleared -
      the message block. The counterfactual is load-bearing here too: a teleport whose landing
      spot freezes the record freezes both runs, and that is the terrain, not a box;
    * ``stompable`` - the stomp harmed a *running* sprite: it died (status below the running
      band, or gone) or changed state inside it (the Rex flattens, `9 -> 8`). A status change
      out of the spawn list does not count, and meeting only running slots (status >= 8) is
      what keeps that from ever being read as a stomp - the first sweep met dormant slots and
      their wake-up (`1 -> 8`) painted empty shells and the message block as enemies;
    * ``platform`` - the stomp held Mario up where the cleared run fell: a solid object;
    * ``neutral`` - the engine ignored the contact.
    """
    if not contact.get("ran") and not stomp.get("ran"):
        return "unprobed"
    hurts = contact.get("mario_died") and not contact_without.get("mario_died")
    kills_from_above = stomp.get("mario_died") and not stomp_without.get("mario_died")
    if hurts or kills_from_above:
        return "hostile"
    froze = (contact.get("froze_the_player") and not contact_without.get("froze_the_player")) or (
        stomp.get("froze_the_player") and not stomp_without.get("froze_the_player")
    )
    if froze:
        return "interact"
    if stomp.get("ran"):
        before = int(stomp.get("sprite_status_before") or 0)
        after = stomp.get("sprite_status_after")
        died = stomp.get("sprite_gone") or (after is not None and after < wram.SPRITE_STATUS_ACTIVE)
        harmed = before >= wram.SPRITE_STATUS_ACTIVE and after is not None and after != before
        if (died or harmed) and before >= wram.SPRITE_STATUS_ACTIVE:
            return "stompable"
        if stomp.get("held_up") and not stomp_without.get("held_up"):
            return "platform"
    return "neutral"


def main() -> Dict[str, Any]:
    parser = argparse.ArgumentParser(description="Measure what the stages' sprites do to Mario.")
    parser.add_argument(
        "--ids", type=str, default=None, help="comma-separated sprite ids; default: all seen"
    )
    parser.add_argument("--output", default=results_file("sprite_behavior_probe_metrics.json"))
    parser.add_argument(
        "--emit-table",
        action="store_true",
        help="also rewrite src/environment/sprite_behavior_table.py from the measurements",
    )
    args = parser.parse_args()
    wanted = {int(part, 0) for part in args.ids.split(",")} if args.ids else None

    emu = SnesLibretroEmulator(CORE_PATH)
    emu.load_rom(ROM_PATH)
    frames: Dict[int, Tuple[str, bytes]] = {}
    where: Dict[int, str] = {}

    def note_new_sprites(tag: str) -> None:
        missing = (wanted - set(frames)) if wanted is not None else None
        for sprite in sprite_slots(emu, plausible_only=True):
            sid = sprite["id"]
            if wanted is not None and sid not in missing:
                continue
            if sid in frames:
                continue
            frames[sid] = (tag, emu.save_state())
            where[sid] = tag
            logger.info(f"met sprite {sid:#04x} in stage {tag} at ({sprite['x']}, {sprite['y']})")

    # The held-right walk dies in the first pit of the stages that have one, so the middle of
    # Yoshi's Island 1 is unreachable to it - and that is where the Koopas are. The clearance
    # draw of 10.66 crosses the whole stage, so the probe flies it as its second collector:
    # the same controller, the same seed, the same preamble the recorder reproduces.
    from scripts.record_dashboard_run import MpcClearanceActor
    from src.evaluation.evaluate_full_level_clearance import extract_12d_vector

    clearance_tag, clearance_state = "0x2A-clear-draw", STAGES[0][1]
    with open(state_path(clearance_state), "rb") as fh:
        clearance_bytes = fh.read()
    actor = MpcClearanceActor("cuda" if torch.cuda.is_available() else "cpu", seed=7)
    emu.load_state(clearance_bytes)
    for _ in range(10):
        emu.set_input({})
        emu.step_frame()
    for frame in range(9000):
        note_new_sprites(clearance_tag)
        state = emu.get_smw_extended_state()
        mode = emu.get_game_mode()
        if mode != wram.GAME_MODE_INTERACTIVE:
            break
        emu.set_input(actor.act(extract_12d_vector(state), "cpu")[0])
        emu.step_frame()

    for tag, name in STAGES:
        if wanted is not None and not (wanted - set(frames)):
            break
        with open(state_path(name), "rb") as fh:
            state_bytes = fh.read()
        emu.load_state(state_bytes)
        for frame in range(WALK_FRAMES):
            note_new_sprites(tag)
            emu.set_input({"RIGHT": True, "Y": True, "B": frame % 24 == 0})
            emu.step_frame()
            if emu.get_game_mode() != wram.GAME_MODE_INTERACTIVE:
                break

    records: List[Dict[str, Any]] = []
    for sid in sorted(frames):
        tag, frame_bytes = frames[sid]
        contact = contact_probe(emu, frame_bytes, sid, with_sprite=True)
        contact_without = contact_probe(emu, frame_bytes, sid, with_sprite=False)
        stomp = stomp_probe(emu, frame_bytes, sid, with_sprite=True)
        stomp_without = stomp_probe(emu, frame_bytes, sid, with_sprite=False)
        records.append(
            {
                "sprite": f"{sid:#04x}",
                "met_in_stage": tag,
                "contact": contact,
                "contact_without_sprite": contact_without,
                "stomp": stomp,
                "stomp_without_sprite": stomp_without,
                "class": classify(contact, contact_without, stomp, stomp_without),
            }
        )
        logger.info(f"sprite {sid:#04x} -> {records[-1]['class']}")
    emu.close()

    counts: Dict[str, int] = {}
    for record in records:
        counts[record["class"]] = counts.get(record["class"], 0) + 1
    payload = {
        "study": (
            "What the engine itself does when Mario touches every sprite id the recorded stages "
            "spawn, measured by meeting each sprite in its own stage and reading the console's "
            "death, power-up, coin and sprite-status responses to a side contact and a stomp."
        ),
        "protocol": {
            "stages": [name for _, name in STAGES],
            "walk_frames": WALK_FRAMES,
            "contact_frames": CONTACT_FRAMES,
            "ids_probed": len(records),
            "class_rule": (
                "hostile: the contact or the stomp killed a small Mario with the sprite present "
                "and not with its slot cleared (a fall past the floor kills both runs and says "
                "nothing about the sprite); interact: the engine froze the whole player record "
                "with the mode still 0x14 (10.63's box signature) with the sprite present and "
                "not with its slot cleared - a teleport that freezes both runs is the landing "
                "spot, not a box; "
                "stompable: the stomp harmed a running sprite - it died (status below the "
                "running band or gone) or changed state inside it, like the Rex flattening; "
                "platform: the stomp held Mario up where the cleared run fell; neutral: the "
                "engine ignored the contact. Only slots the engine is running (status >= 8) are "
                "ever met: the first sweep met dormant slots (status 1) and read their wake-up "
                "as a stomp, which painted empty shells and the message block as enemies"
            ),
        },
        "sprites": records,
        "class_counts": counts,
    }
    write_metrics(args.output, payload, command="python -m scripts.probe_sprite_behaviors")
    if args.emit_table:
        logger.info(f"sprite behavior table: {emit_table(records)}")
    logger.info(f"sprite behavior probe: {counts}")
    return payload


if __name__ == "__main__":
    main()
