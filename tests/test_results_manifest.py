    """The engine-rules baseline must not beat the Hard PINN (that would falsify 8.1)."""
    published = json.loads((RESULTS / "benchmark_metrics.json").read_text(encoding="utf-8"))
    hard = published["single_step_results"]["Hard_Residual_PINN"]["test_loss_data"]
