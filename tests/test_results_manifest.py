def test_declared_inputs_are_not_newer_than_the_result():
    """A checkpoint regenerated after a closed-loop run invalidates that run.

    The freshness block in MANIFEST.md declares which checkpoints each artifact
    loads. This gate recomputes the git commit order and requires the `STALE`
    marker to match reality in both directions: an unmarked row that is actually
    stale fails, and a marked row that was re-run must be un-marked.

    Ordering needs real history. A single-commit checkout (the historical
    `actions/checkout` default) makes every path look as if the same commit added
    it, so the gate would judge every pair a tie; CI therefore fetches the full
    history (`fetch-depth: 0`) and shallow clones skip instead of lying.
    """
    if _history_is_grafted() or _visible_commit_count() < 2:
        pytest.skip(
            "commit order is not observable in this checkout "
            f"(visible commits: {_visible_commit_count()})"
        )
    rows = _freshness_rows(_manifest_text())
    assert rows, "MANIFEST.md declares no checkpoint dependencies"
    checked = 0
    for row in rows:
        artifact_stamp = _commit_timestamp(f"results/{row['artifact']}")
        if artifact_stamp is None:
            continue  # generated but not committed yet: no ordering to verify
        stamps = []
        for dep in row["deps"]:
            stamp = _commit_timestamp(f"results/checkpoints/{dep}")
            if stamp is not None and (CHECKPOINTS / dep).is_file():
                stamps.append(stamp)
        if not stamps:
            continue
        checked += 1
        actually_stale = max(stamps) > artifact_stamp
        assert actually_stale == row["stale"], (
            f"results/{row['artifact']} is "
            f"{'stale (a dependency checkpoint was regenerated after it)' if actually_stale else 'current'}; "
            f"the MANIFEST.md {'STALE marker is wrong - re-run the command' if actually_stale else 'marker is obsolete - drop it'}"
            f" declared for it."
        )
    assert checked, "no freshness row could be verified against git history"


@pytest.mark.parametrize("artifact,keypath,fmt", QUOTED_HEADLINES)
def test_readme_quotes_the_committed_numbers(artifact: str, keypath: list[str], fmt: str) -> None:
    """Every §10 headline in README.md must be the number the artifact really holds."""
    file = RESULTS / artifact
    if not file.is_file():
        pytest.skip(f"{artifact} not generated yet")
    node: Any = json.loads(file.read_text(encoding="utf-8"))
    for key in keypath:
        assert isinstance(node, dict) and key in node, f"{artifact} has no key {key!r}"
        node = node[key]
    rendered = fmt.format(node)
    text = README.read_text(encoding="utf-8")
    assert rendered in text, (
        f"README.md no longer contains {rendered!r} "
        f"({artifact}:{'/'.join(keypath)} = {node!r}). Either the artifact was "
        "regenerated (update the prose and the 10.27 table) or the prose drifted from "
        "the evidence."
    )


