def _manifest_text() -> str:
    if not MANIFEST.is_file():
        pytest.skip(f"{MANIFEST} not present")
    return MANIFEST.read_text(encoding="utf-8")


def _table_rows(text: str) -> list[dict[str, str]]:
    rows = []
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 4 or not cells[0].startswith("`"):
            continue  # header / separator rows
        artifact = cells[0].strip("`")
        writers = [w.strip().strip("`") for w in cells[1].split(",")]
        rows.append(
            {
                "artifact": artifact,
                "writers": writers,  # type: ignore[assignment]
                "emulator": cells[2],
                "section": cells[3],
            }
        )
    return rows


def _legacy_allowance(text: str) -> set[str]:
    block = re.search(r"```text\n(.*?)\n```", text, re.S)
    if not block:
        return set()
    return {token for token in block.group(1).split() if token.endswith(".json")}


def _freshness_rows(text: str) -> list[dict[str, object]]:
    """Parse the ```freshness block: 'STALE <artifact> <- <ckpt> <ckpt> ...'."""
    block = re.search(r"```freshness\n(.*?)\n```", text, re.S)
    if not block:
        return []
    rows = []
    for line in block.group(1).splitlines():
        line = line.strip()
        if not line or "<-" not in line:
            continue
        stale = line.startswith("STALE")
        artifact, _, deps = line.removeprefix("STALE").partition("<-")
        rows.append(
            {
                "artifact": artifact.strip(),
                "stale": stale,
                "deps": [d.strip() for d in deps.split() if d.strip()],
            }
        )
    return rows


def _commit_timestamp(relative: str) -> int | None:
    """Last-write time of a path: its commit time, or its mtime while uncommitted.

    A regenerated-but-not-yet-committed artifact still carries the timestamp of the
    older commit for that path, which would make it look stale; the working tree
    knows better, so a dirty path is timed by modification instead.
    """
    if shutil.which("git") is None:
        return None
    target = REPO_ROOT / relative
    dirty = subprocess.run(
        ["git", "status", "--porcelain", "--", relative],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if dirty and target.is_file():
        return int(target.stat().st_mtime)
    proc = subprocess.run(
        ["git", "log", "-1", "--format=%ct", "--", relative],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    stamp = proc.stdout.strip()
    return int(stamp) if proc.returncode == 0 and stamp else None


def _visible_commit_count() -> int:
    """How many commits git can reach from HEAD (0 when git is unavailable)."""
    if shutil.which("git") is None:
        return 0
    proc = subprocess.run(
        ["git", "rev-list", "--count", "HEAD"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    stamp = proc.stdout.strip()
    return int(stamp) if proc.returncode == 0 and stamp.isdigit() else 0


def _history_is_grafted() -> bool:
    """True for a shallow clone, where older commits are replaced by a graft."""
    gitdir = REPO_ROOT / ".git"
    return gitdir.is_dir() and (gitdir / "shallow").is_file()


def _on_disk() -> set[str]:
    return {p.name for p in RESULTS.glob("*.json")}


def _mentions(body: str, artifact: str) -> bool:
    """True if the module contains this artifact's name, however it is composed.

    Several writers build the filename at runtime (``f"online_mbpo{suffix}_metrics
    .json"`` for both the safe and unsafe runs), so a literal substring search
    would reject a mapping that is perfectly correct. Prefix/suffix matching keeps
    the check meaningful while allowing an arbitrary middle segment.
    """
    if artifact in body:
        return True
    tokens = artifact.removesuffix(".json").split("_")
    for prefix_len in range(1, len(tokens)):
        for suffix_start in range(prefix_len + 1, len(tokens) + 1):
            prefix = "_".join(tokens[:prefix_len])
            suffix = "_".join(tokens[suffix_start:])
            pattern = re.escape(prefix) + r"[\w{}.$-]*" + re.escape(suffix) + r"\.json"
            if re.search(pattern, body):
                return True
    return False


def test_every_artifact_on_disk_is_catalogued():
    catalogued = {row["artifact"] for row in _table_rows(_manifest_text())}
    orphans = sorted(_on_disk() - catalogued)
    assert not orphans, f"results artifacts missing from MANIFEST.md: {orphans}"


def test_every_catalogued_artifact_exists():
    rows = _table_rows(_manifest_text())
    assert rows, "MANIFEST.md table could not be parsed"
    missing = [
        row["artifact"]
        for row in rows
        if not (RESULTS / row["artifact"]).is_file() and PENDING_MARKER not in row["section"]
    ]
    assert not missing, f"MANIFEST.md lists artifacts that do not exist: {missing}"


def test_declared_writer_actually_mentions_the_artifact():
    for row in _table_rows(_manifest_text()):
        for writer in row["writers"]:
            # "src/training/online_mbpo.py --safe" -> module path + ignored flags
            module = writer.split()[0]
            path = REPO_ROOT / module
            assert path.is_file(), f"{row['artifact']}: writer {module} does not exist"
            body = path.read_text(encoding="utf-8", errors="replace")
            assert _mentions(body, row["artifact"]), (
                f"{module} is catalogued as the writer of {row['artifact']} but never "
                "constructs that name; fix the manifest or the script, do not leave "
                "the claim dangling."
            )


